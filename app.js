async function copyText(value, label, sourceElement = null) {
  const copied = await writeToClipboard(value);

  if (sourceElement) {
    const hint = sourceElement.querySelector(".copy-hint");
    sourceElement.classList.toggle("copied", copied);
    if (hint) {
      const oldText = hint.textContent;
      hint.textContent = copied ? "copied" : "copy failed";
      window.setTimeout(() => {
        hint.textContent = oldText;
        sourceElement.classList.remove("copied");
      }, 1500);
    }
    return;
  }

  printLine(
    copied ? `${label} copied to clipboard.` : `Unable to copy ${label}.`,
    copied ? "success" : "error"
  );
}

async function writeToClipboard(value) {
  try {
    if (navigator.clipboard && window.isSecureContext) {
      await navigator.clipboard.writeText(value);
      return true;
    }
  } catch (error) {
    // Fall back to the legacy copy path below.
  }

  const textarea = document.createElement("textarea");
  textarea.value = value;
  textarea.setAttribute("readonly", "");
  textarea.style.position = "fixed";
  textarea.style.opacity = "0";
  document.body.appendChild(textarea);
  textarea.focus();
  textarea.select();

  let copied = false;

  try {
    copied = document.execCommand("copy");
  } catch (error) {
    copied = false;
  }

  document.body.removeChild(textarea);
  focusInput();
  return copied;
}

function escapeHtml(value) {
  return value
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;");
}

function slugify(value) {
  return value.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");
}

function delay(ms) {
  return new Promise((resolve) => window.setTimeout(resolve, ms));
}
