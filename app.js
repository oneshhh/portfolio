function buildContactEntries(data) {
  const entries = [
    { label: "Name", value: data.name, copyable: false },
    { label: "Role", value: `${data.title} @ ${data.company}`, copyable: false },
    { label: "Age", value: String(data.age), copyable: false },
    { label: "DOB", value: data.dob, copyable: false },
    { label: "Email", value: data.email, copyable: true },
    { label: "Phone", value: data.phone, copyable: true },
    { label: "Location", value: data.location, copyable: true },
    { label: "GitHub", value: data.github, copyable: true }
  ];

  if (data.linkedin) {
    entries.push({ label: "LinkedIn", value: data.linkedin, copyable: true });
  }

  if (data.website) {
    entries.push({ label: "Website", value: data.website, copyable: true });
  }

  if (data.blog) {
    entries.push({ label: "Blog", value: data.blog, copyable: true });
  }

  return entries;
}

function buildLinkLines(data) {
  return [
    `github   ${data.github}`,
    data.blog ? `blog     ${data.blog}` : null,
    data.linkedin ? `linkedin ${data.linkedin}` : null,
    data.website ? `website  ${data.website}` : null
  ].filter(Boolean);
}

function buildSkillsText(skills) {
  return Object.entries(skills).map(([key, values], index, entries) => {
    return [
      formatSectionHeading(key),
      ...values.map((value) => `- ${value}`),
      index < entries.length - 1 ? SECTION_SEPARATOR : null
    ].filter(Boolean).join("\n");
  }).join("\n\n");
}

