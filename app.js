function tokenize(input) {
  return input.match(/(?:[^\s"]+|"[^"]*")+/g)?.map((token) => {
    return token.startsWith("\"") && token.endsWith("\"") ? token.slice(1, -1) : token;
  }) || [];
}

function resolvePath(input) {
  const normalizedInput = input === "~" ? "/" : input.replace(/^~\//, "/");
  const loweredInput = normalizedInput.toLowerCase();

  if (loweredInput === "/root" || loweredInput === "root") {
    return { segments: [], isRootAlias: true };
  }

  const isAbsolute = normalizedInput.startsWith("/");
  const base = isAbsolute ? [] : [...state.currentPath];
  const chunks = normalizedInput.split("/").filter(Boolean);

  for (const chunk of chunks) {
    if (chunk === ".") {
      continue;
    }

    if (chunk === "..") {
      base.pop();
      continue;
    }

    base.push(chunk);
  }

  return { segments: base, isRootAlias: false };
}

function getNode(segments) {
  let current = filesystem;

  for (const segment of segments) {
    if (!current || current.type !== "dir") {
      return null;
    }

    current = current.children.find((child) => {
      return child.name.toLowerCase() === segment.toLowerCase();
    }) || null;
  }

  return current;
}

