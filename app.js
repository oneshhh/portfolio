function formatEntries(entries) {
  return entries.map((entry) => {
    return `${entry.label.toLowerCase().padEnd(8, " ")} ${entry.value}`;
  }).join("\n");
}

function formatSectionHeading(value) {
  return value
    .replace(/([A-Z])/g, " $1")
    .replace(/[-_]+/g, " ")
    .replace(/^./, (character) => character.toUpperCase());
}

function dir(name, children = []) {
  return { type: "dir", name, children };
}

function file(name, content, options = {}) {
  return { type: "file", name, content, ...options };
}

function link(name, label, url) {
  return { type: "link", name, label, url, content: `${label}\n${url}` };
}

async function runBootSequence() {
  elements.input.disabled = true;

  for (const entry of bootSequence) {
    printLine(entry.text, entry.className);
    await delay(120);
  }

  state.booted = true;
  elements.sessionStatus.textContent = "ready";
  elements.input.disabled = false;
  updatePrompt();
  printSpacer();
  commandHome();
  printSpacer();
  focusInput();
}

function handleSubmit(event) {
  event.preventDefault();
  if (!state.booted) {
    return;
  }

  const raw = elements.input.value.trim();
  printCommand(raw);

  if (raw) {
    state.history.push(raw);
  }

  state.historyIndex = state.history.length;
  elements.input.value = "";

  if (!raw) {
    printSpacer();
    return;
  }

  execute(raw);
}

function handleOutputClick(event) {
  const target = event.target.closest("[data-copy]");
  if (target) {
    copyText(target.dataset.copy, target.dataset.label || "Value", target);
    return;
  }

  const openTarget = event.target.closest("[data-open]");
  if (!openTarget) {
    return;
  }

  window.open(openTarget.dataset.open, "_blank", "noopener,noreferrer");
}

function handleKeydown(event) {
  if (!state.booted) {
    return;
  }

  if (event.key === "ArrowUp") {
    event.preventDefault();
    if (state.historyIndex > 0) {
      state.historyIndex -= 1;
      elements.input.value = state.history[state.historyIndex] || "";
    }
  }

  if (event.key === "ArrowDown") {
    event.preventDefault();
    if (state.historyIndex < state.history.length - 1) {
      state.historyIndex += 1;
      elements.input.value = state.history[state.historyIndex] || "";
    } else {
      state.historyIndex = state.history.length;
      elements.input.value = "";
    }
  }

  if (event.key === "Tab") {
    event.preventDefault();
    autocompleteInput();
  }
}

function execute(raw) {
  const tokens = tokenize(raw);
  const name = tokens[0]?.toLowerCase();
  const args = tokens.slice(1);

  if (!name) {
    printSpacer();
    return;
  }

  const command = commands[name];
  if (!command) {
    const suggestion = suggestCommand(name);
    printLine(
      suggestion
        ? `command not found: ${name}. Did you mean '${suggestion}'?`
        : `command not found: ${name}. Type 'help' to see available commands.`,
      "error"
    );
    printSpacer();
    return;
  }

  command(args);
  printSpacer();
  scrollOutput();
  focusInput();
}

