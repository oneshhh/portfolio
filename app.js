function formatPath(segments) {
  return segments.length ? `/${segments.join("/")}` : "~";
}

function buildTreeLines(node, prefix = "") {
  if (node.type !== "dir") {
    return [];
  }

  const sorted = node.children.slice().sort(sortNodes);
  return sorted.flatMap((child, index) => {
    const isLast = index === sorted.length - 1;
    const connector = isLast ? "`-- " : "|-- ";
    const line = `${prefix}${connector}${child.type === "dir" ? `${child.name}/` : child.name}`;

    if (child.type !== "dir") {
      return [line];
    }

    const nextPrefix = `${prefix}${isLast ? "    " : "|   "}`;
    return [line, ...buildTreeLines(child, nextPrefix)];
  });
}

function walk(node, pathSegments, callback) {
  callback(node, pathSegments);
  if (node.type !== "dir") {
    return;
  }

  node.children.forEach((child) => {
    walk(child, [...pathSegments, child.name], callback);
  });
}

function sortNodes(a, b) {
  if (a.type === "dir" && b.type !== "dir") {
    return -1;
  }

  if (a.type !== "dir" && b.type === "dir") {
    return 1;
  }

  return a.name.localeCompare(b.name);
}

function autocompleteInput() {
  const current = elements.input.value;
  const tokens = tokenize(current);

  if (!tokens.length || /\s$/.test(current)) {
    return;
  }

  if (tokens.length === 1) {
    const needle = tokens[0].toLowerCase();
    const matches = Object.keys(commands).filter((command) => command.startsWith(needle));
    if (matches.length === 1) {
      elements.input.value = `${matches[0]} `;
    } else if (matches.length > 1) {
      printLine(matches.join("    "), "dim");
      printSpacer();
    }
    return;
  }

  const target = tokens[tokens.length - 1];
  const suggestions = getPathSuggestions(target);
  if (suggestions.length === 1) {
    const completed = suggestions[0];
    const nextTokens = [...tokens.slice(0, -1), completed];
    elements.input.value = nextTokens.join(" ");
  } else if (suggestions.length > 1) {
    printLine(suggestions.join("    "), "dim");
    printSpacer();
  }
}

function getPathSuggestions(target) {
  const isAbsolute = target.startsWith("/");
  const rawSegments = target.split("/");
  const needle = rawSegments.pop() || "";
  const baseSegments = rawSegments.filter(Boolean);
  const parentSegments = isAbsolute ? baseSegments : [...state.currentPath, ...baseSegments];
  const parentNode = getNode(parentSegments);

  if (!parentNode || parentNode.type !== "dir") {
    return [];
  }

  return parentNode.children
    .filter((child) => child.name.toLowerCase().startsWith(needle.toLowerCase()))
    .map((child) => {
      const name = child.type === "dir" ? `${child.name}/` : child.name;
      const prefix = isAbsolute ? `/${baseSegments.join("/")}` : rawSegments.join("/");
      if (!prefix) {
        return name;
      }
      return `${prefix}/${name}`.replace("//", "/");
    });
}

